"""Transactional storage for the backend. SQLite remains available for local development."""
from contextlib import contextmanager
from pathlib import Path
import re
import sqlite3

from psycopg import Error as PostgresError, IntegrityError as PostgresIntegrityError, sql
from psycopg.rows import dict_row
from psycopg_pool import ConnectionPool, PoolTimeout

INTEGRITY_ERRORS = (sqlite3.IntegrityError, PostgresIntegrityError)
MIGRATIONS = Path(__file__).with_name("migrations")
WRITE_LOCK = 658749360


class Connection:
    def __init__(self, raw, postgres):
        self.raw = raw
        self.postgres = postgres

    def execute(self, query, params=()):
        if self.postgres:
            query = query.replace("?", "%s")
        return self.raw.execute(query, params)

    def executemany(self, query, rows):
        if self.postgres:
            with self.raw.cursor() as cursor:
                cursor.executemany(query.replace("?", "%s"), rows)
        else:
            self.raw.executemany(query, rows)

    def write_lock(self):
        # Preserve SQLite's serialized read/modify/write operations on PostgreSQL.
        # This leaves ordinary reads and single-statement updates concurrent.
        if self.postgres:
            self.execute("SELECT pg_advisory_xact_lock(?)", (WRITE_LOCK,))
        else:
            self.execute("BEGIN IMMEDIATE")

    def read_snapshot(self):
        self.execute("SET TRANSACTION ISOLATION LEVEL REPEATABLE READ" if self.postgres else "BEGIN")

    @property
    def submission_day(self):
        if self.postgres:
            return "CAST(to_timestamp(r.submitted) AT TIME ZONE 'Asia/Tashkent' AS DATE)"
        return "date(r.submitted,'unixepoch','+05:00')"

    def advance_identity(self, table):
        if self.postgres:
            self.raw.execute(sql.SQL("""
                SELECT setval(pg_get_serial_sequence(%s, 'id'),
                    COALESCE(MAX(id), 1), COUNT(*) > 0) FROM {}
            """).format(sql.Identifier(table)), (table,))


class Database:
    def __init__(self, target):
        self.postgres = isinstance(target, str) and target.startswith(("postgresql://", "postgres://"))
        if self.postgres:
            self.pool = ConnectionPool(target, min_size=1, max_size=8, timeout=10, open=False,
                                       kwargs={"row_factory": dict_row, "connect_timeout": 5})
            self.pool.open(wait=True, timeout=15)
        else:
            self.pool = None
            self.path = Path(target).resolve()
            self.path.parent.mkdir(parents=True, exist_ok=True)
            with self.connect() as db:
                db.execute("PRAGMA journal_mode = WAL")

    @contextmanager
    def connect(self):
        if self.pool:
            with self.pool.connection() as connection:
                yield Connection(connection, self.postgres)
            return
        raw = sqlite3.connect(self.path, timeout=10)
        raw.row_factory = sqlite3.Row
        try:
            raw.execute("PRAGMA foreign_keys = ON")
            with raw:
                yield Connection(raw, False)
        finally:
            raw.close()

    def close(self):
        if self.pool:
            self.pool.close()

    def ready(self):
        try:
            with self.connect() as db:
                db.execute("SELECT 1").fetchone()
            return True
        except (sqlite3.Error, PostgresError, PoolTimeout):
            return False

    def migrate(self, version, *, field_visit_column=False):
        unique_schema = MIGRATIONS / f"{version}.postgres.sql"
        filename = unique_schema if self.postgres and unique_schema.is_file() else MIGRATIONS / f"{version}.sql"
        schema = filename.read_text(encoding="utf-8")
        if self.postgres:
            schema = re.sub(r"\bid INTEGER PRIMARY KEY", "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", schema)
            schema = re.sub(r"\bINTEGER\b", "BIGINT", schema)
            schema = re.sub(r"\bBLOB\b", "BYTEA", schema)
        with self.connect() as db:
            db.write_lock()
            db.execute("CREATE TABLE IF NOT EXISTS schema_migrations (version TEXT PRIMARY KEY)")
            if db.execute("SELECT version FROM schema_migrations WHERE version=?", (version,)).fetchone():
                return
            for statement in schema.split(";"):
                if statement.strip():
                    db.execute(statement)
            if field_visit_column:
                if self.postgres:
                    db.execute("ALTER TABLE reports ADD COLUMN IF NOT EXISTS visit_id BIGINT REFERENCES field_visits(id)")
                elif "visit_id" not in {row["name"] for row in db.execute("PRAGMA table_info(reports)")}:
                    db.execute("ALTER TABLE reports ADD COLUMN visit_id INTEGER REFERENCES field_visits(id)")
                db.execute("CREATE INDEX IF NOT EXISTS reports_visit ON reports(visit_id)")
            db.execute("INSERT INTO schema_migrations(version) VALUES (?)", (version,))
